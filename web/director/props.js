// 言葉 → 種類 を、長い言葉から順に並べたもの（同じ言葉が2つにあれば、表で先のもの）
const WORDS = (() => {
  const out = [];
  const seen = new Set();
  PROPS.forEach(([kind, , ...words]) => { for (const w of words) if (w && !seen.has(w)) { seen.add(w); out.push([w, kind]); } });
  return out.sort((a, b) => Array.from(b[0]).length - Array.from(a[0]).length);
})();
export const PROP_LABELS = Object.freeze(Object.fromEntries(PROPS.map(([kind, label]) => [kind, label])));

/**
 * 行の文字から、連想する小物の種類を出てくる順に最大 max 個（同じ種類は1つ）。
 * 長い言葉が先に場所を取り、重なる短い言葉は数えない（「電車」の「車」は車にならない）
 */
export function propsOf(text, max = 2) {
  const s = String(text ?? '');
  if (!s || !(max > 0)) return [];
  const used = new Array(s.length).fill(false);
  const hits = [];
  for (const [w, kind] of WORDS) {
    let from = 0;
    for (;;) {
      const at = s.indexOf(w, from);
      if (at < 0) break;
      from = at + 1;
      let free = true;
      for (let k = at; k < at + w.length; k++) if (used[k]) { free = false; break; }
      if (!free) continue;
      for (let k = at; k < at + w.length; k++) used[k] = true;
      hits.push({ at, kind });
    }
  }
  hits.sort((a, b) => a.at - b.at);
  const out = [];
  for (const h of hits) { if (!out.includes(h.kind)) out.push(h.kind); if (out.length >= max) break; }
  return out;
}
